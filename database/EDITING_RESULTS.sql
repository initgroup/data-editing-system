 WHERE G.RESULT_FAMILY = :family
   AND (:source = 'ALL' OR G.SOURCE_FAMILY = :source)
   AND (:allConditions = 'Y' OR NVL(G.FILTER_CONDITION_COUNT, -1) = :conditionCount)
   AND (:excludeZero = 'N' OR G.REVIEW_VIOLATION_COUNT IS NULL OR G.REVIEW_VIOLATION_COUNT <> 0)
