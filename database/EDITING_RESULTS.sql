-- [EDITING_ASSOC_SOURCE]
SELECT R.*
     , R.OWNER AS SCOPE_RULE_OWNER
     , R.TARGET_OWNER AS SCOPE_TARGET_OWNER
     , R.TARGET_TABLE AS SCOPE_TARGET_TABLE
     , R.RESULT_COLUMN AS SCOPE_TARGET_COLUMN
     , CASE WHEN R.RULE_SOURCE = 'MIXED_PATTERN_TREE' THEN 'MIXED_PATTERN' ELSE 'LEGACY_ASSOC' END AS SOURCE_FAMILY
     , CASE
           WHEN R.RULE_SOURCE = 'MIXED_PATTERN_TREE' AND R.RESULT_KIND = 'FORMULA' THEN 'FORMULA'
           WHEN R.RULE_SOURCE = 'MIXED_PATTERN_TREE' AND R.RESULT_KIND IN ('VALUE', 'RANGE') THEN 'CONDITION'
           WHEN NVL(R.RULE_SOURCE, '-') <> 'MIXED_PATTERN_TREE' AND NVL(R.RESULT_KIND, 'VALUE') <> 'FORMULA' THEN 'CONDITION'
           ELSE 'UNCLASSIFIED'
       END AS RESULT_FAMILY
  FROM INIT$_TB_RULEDISC_ASSOC_SUM R
 WHERE 1=1
   AND R.RUN_SOURCE_TYPE = 'FLOW_WORK'
   AND R.RUN_ID = :runId
   AND (:owner IS NULL OR R.TARGET_OWNER = :owner)
   AND (:tableName IS NULL OR R.TARGET_TABLE = :tableName)
;

