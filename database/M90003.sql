WITH PROFILE_COUNTS AS
     (
      SELECT F.OWNER
           , F.TABLE_NAME
           , F.COLUMN_NAME
           , SUM(F.HASH_COUNT) AS PROFILE_COUNT
           , SUM(
                 CASE
                     WHEN F.PROFILE_HASH IS NULL THEN 0
                     ELSE GREATEST(F.HASH_COUNT - 1, 0)
                 END
             ) AS DUPLICATE_COUNT
        FROM
           (
            SELECT F0.OWNER
                 , F0.TABLE_NAME
                 , F0.COLUMN_NAME
                 , F0.PROFILE_HASH
                 , COUNT(*) AS HASH_COUNT
              FROM "INIT$_TB_COLTYPE_PROFILE" F0
             WHERE 1=1
               AND F0.FEATURE_VERSION = 'V2'
             GROUP BY F0.OWNER
                    , F0.TABLE_NAME
                    , F0.COLUMN_NAME
                    , F0.PROFILE_HASH
           ) F
       GROUP BY F.OWNER
              , F.TABLE_NAME
              , F.COLUMN_NAME
     )
   , CONFIRMED_PROFILE AS
     (
      SELECT F.*
        FROM "INIT$_TB_COLTYPE_PROFILE" F
       WHERE 1=1
         AND F.FEATURE_VERSION = 'V2'
     )
