     , M.ACTUAL_CLASS_CODE AS TYPE_CODE
     , M.PREDICTED_CLASS_CODE AS PREDICTED_TYPE_CODE
     , M.CLASS_GROUP_CODE AS TYPE_GROUP_CODE
     , M.METRIC_NAME
     , M.METRIC_VALUE
     , M.SUPPORT_COUNT
