           , P.SAMPLE_ROWS
           , P.SAMPLE_NOT_NULL_ROWS
           , P.NUM_DISTINCT
           , P.SAMPLE_DISTINCT
           , P.DISTINCT_RATIO AS DIST_VAL_RT
           , P.NULL_RATIO
           , P.LOG_DATA_TYPE
           , P.ENTROPY
           , P.NORM_ENTROPY
           , P.NUMERIC_RATIO
           , P.INTEGER_RATIO
           , P.MIN_NUM_VALUE
           , P.MAX_NUM_VALUE
           , P.AVG_TEXT_LENGTH
           , P.MAX_TEXT_LENGTH
           , L.TYPE_CODE
           , L.TYPE_GROUP_CODE
           , L.DISPLAY_TYPE_VALUE
           , L.LABEL_SOURCE
           , L.CONFIRMED_YN
           , L.LABEL_CONFIDENCE
           , L.LABEL_REASON
           , L.CONFIRMED_BY
           , L.CONFIRMED_AT
           , L.UPDATED_AT
           , NVL(C.PROFILE_COUNT, 0) AS PROFILE_COUNT
