                 WHEN R.STATUS_CODE = 'ACTIVE' THEN 'ARCHIVED'
                 ELSE R.STATUS_CODE
             END AS EFFECTIVE_STATUS_CODE
           , ROW_NUMBER() OVER (
                 ORDER BY CASE
                              WHEN A.MODEL_VERSION_ID = R.MODEL_VERSION_ID THEN 0
                              WHEN R.STATUS_CODE = 'CANDIDATE' THEN 1
                              ELSE 2
