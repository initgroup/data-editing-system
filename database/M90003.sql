        FROM ELIGIBLE_PROFILE E
     )
   , DEDUP_ELIGIBLE AS
     (
      SELECT DISTINCT E.FEATURE_SIGNATURE
           , E.DATA_TYPE
           , E.TOTAL_ROWS
           , E.NON_NULL_ROWS
           , E.SAMPLE_ROWS
           , E.SAMPLE_NOT_NULL_ROWS
           , E.NUM_DISTINCT
           , E.SAMPLE_DISTINCT
           , E.DIST_VAL_RT
