           (
            SELECT R.*
                 , ROW_NUMBER() OVER (
                       PARTITION BY R.RUN_SOURCE_TYPE, R.RUN_ID, R.OWNER, R.TABLE_NAME, R.COLUMN_NAME
                           ORDER BY R.CREATE_DT DESC
                                  , NVL(R.MODEL_VERSION_ID, -1) DESC
                                  , R.MODEL_NAME DESC
