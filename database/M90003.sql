           , E.NUMERIC_RATIO
           , E.INTEGER_RATIO
           , E.MIN_NUM_VALUE
           , E.MAX_NUM_VALUE
           , E.AVG_TEXT_LENGTH
           , E.MAX_TEXT_LENGTH
           , E.TYPE_CODE
        FROM SIGNED_ELIGIBLE E
