  JOIN "INIT$_TB_OML_MODEL_METRIC" M
    ON M.MODEL_VERSION_ID = A.MODEL_VERSION_ID
 WHERE 1=1
   AND A.MODEL_KEY = :modelKey
 ORDER BY M.SPLIT_CODE
        , NVL(M.CLASS_GROUP_CODE, '~')
        , NVL(M.ACTUAL_CLASS_CODE, '~')
        , NVL(M.PREDICTED_CLASS_CODE, '~')
        , M.METRIC_NAME
;

