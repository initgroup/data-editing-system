                 :statusCode = 'ALL'
              OR CASE
                     WHEN A.MODEL_VERSION_ID = R.MODEL_VERSION_ID THEN 'ACTIVE'
                     WHEN R.STATUS_CODE = 'ACTIVE' THEN 'ARCHIVED'
                     ELSE R.STATUS_CODE
                 END = :statusCode
