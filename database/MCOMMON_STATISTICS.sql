WITH COLUMN_BOUNDS AS
(
    /* --DYNAMIC_BOUNDS-- */
)
, NORMALIZED_VALUES AS
(
    SELECT /*+ MATERIALIZE NO_PARALLEL(T) */
           /* --DYNAMIC_COLUMNS-- */
      FROM /* --DYNAMIC_TABLE-- */ T
)
, LONG_VALUES AS
(
    SELECT /*+ MATERIALIZE */ COLUMN_NAME
         , NUMERIC_VALUE
      FROM NORMALIZED_VALUES
   UNPIVOT INCLUDE NULLS
     (
       NUMERIC_VALUE FOR COLUMN_NAME IN
       (
         /* --DYNAMIC_UNPIVOT-- */
       )
     )
)
, BUCKETED_VALUES AS
(
    SELECT V.COLUMN_NAME
         , CASE
               WHEN B.MAX_VALUE = B.MIN_VALUE THEN 1
               ELSE LEAST(
                        :binCount
                      , GREATEST(
                            1
                          , WIDTH_BUCKET(V.NUMERIC_VALUE, B.MIN_VALUE, B.MAX_VALUE, :binCount)
                        )
                    )
           END AS BUCKET_NO
      FROM LONG_VALUES V
      JOIN COLUMN_BOUNDS B
        ON B.COLUMN_NAME = V.COLUMN_NAME
     WHERE V.NUMERIC_VALUE IS NOT NULL
)
SELECT COLUMN_NAME
     , BUCKET_NO
     , COUNT(*) AS BUCKET_COUNT
  FROM BUCKETED_VALUES
 GROUP BY COLUMN_NAME
        , BUCKET_NO
 ORDER BY COLUMN_NAME
        , BUCKET_NO
;
