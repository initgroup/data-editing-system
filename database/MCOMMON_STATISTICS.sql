SELECT COLUMN_NAME
     , COUNT(*) AS TOTAL_ROW_COUNT
     , COUNT(TEXT_VALUE) AS VALUE_COUNT
     , COUNT(*) - COUNT(TEXT_VALUE) AS NULL_COUNT
     , COUNT(DISTINCT TEXT_VALUE) AS DISTINCT_COUNT
     , COUNT(DISTINCT TEXT_VALUE) / NULLIF(COUNT(TEXT_VALUE), 0) AS DISTINCT_RATE
     , MIN(TEXT_VALUE) AS MIN_TEXT_VALUE
     , MAX(TEXT_VALUE) AS MAX_TEXT_VALUE
     , MIN(LENGTH(TEXT_VALUE)) AS MIN_LENGTH
     , MAX(LENGTH(TEXT_VALUE)) AS MAX_LENGTH
     , AVG(LENGTH(TEXT_VALUE)) AS AVG_LENGTH
  FROM LONG_VALUES
 GROUP BY COLUMN_NAME
 ORDER BY COLUMN_NAME
;

-- [MCOMMON_STATS_TOP_VALUES]
WITH NORMALIZED_VALUES AS
(
    SELECT /*+ MATERIALIZE NO_PARALLEL(T) */
           /* --DYNAMIC_COLUMNS-- */
      FROM /* --DYNAMIC_TABLE-- */ T
)
, LONG_VALUES AS
(
    SELECT /*+ MATERIALIZE */ COLUMN_NAME
         , TEXT_VALUE
      FROM NORMALIZED_VALUES
   UNPIVOT INCLUDE NULLS
     (
       TEXT_VALUE FOR COLUMN_NAME IN
       (
         /* --DYNAMIC_UNPIVOT-- */
       )
     )
)
, VALUE_COUNTS AS
(
    SELECT COLUMN_NAME
         , TEXT_VALUE
         , COUNT(*) AS VALUE_COUNT
      FROM LONG_VALUES
     WHERE TEXT_VALUE IS NOT NULL
     GROUP BY COLUMN_NAME
            , TEXT_VALUE
)
, RANKED_VALUES AS
(
    SELECT V.COLUMN_NAME
         , V.TEXT_VALUE
         , V.VALUE_COUNT
         , ROW_NUMBER() OVER
           (
             PARTITION BY V.COLUMN_NAME
                 ORDER BY V.VALUE_COUNT DESC
                        , V.TEXT_VALUE
           ) AS VALUE_RANK
      FROM VALUE_COUNTS V
)
SELECT COLUMN_NAME
     , TEXT_VALUE
     , VALUE_COUNT
     , VALUE_RANK
  FROM RANKED_VALUES
 WHERE VALUE_RANK <= 10
 ORDER BY COLUMN_NAME
        , VALUE_RANK
;

