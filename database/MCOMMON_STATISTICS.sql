-- [MCOMMON_STATS_VIOLATION_COLUMNS]
WITH VIOLATION_BY_TYPE AS
(
    SELECT V.RESULT_COLUMN AS COLUMN_NAME
         , 'CATEGORICAL' AS RULE_TYPE
         , COUNT(*) AS VIOLATION_COUNT
         , COUNT(DISTINCT NVL(V.CASE_ID, V.CASE_ROWID)) AS VIOLATED_ROW_COUNT
         , COUNT(DISTINCT V.RULE_ID) AS RULE_COUNT
         , MAX(V.VIOLATION_SCORE) AS MAX_VIOLATION_SCORE
      FROM "INIT$_TB_RULEVIOL_ASSOC" V
     WHERE V.RUN_SOURCE_TYPE = :runSourceType
       AND V.RUN_ID = :runId
       AND V.TARGET_OWNER = :targetOwner
       AND V.TARGET_TABLE = :targetTable
       AND V.RESULT_COLUMN IS NOT NULL
     GROUP BY V.RESULT_COLUMN
    UNION ALL
    SELECT V.TARGET_COLUMN AS COLUMN_NAME
         , 'CONTINUOUS' AS RULE_TYPE
         , COUNT(*) AS VIOLATION_COUNT
         , COUNT(DISTINCT NVL(V.CASE_ID, V.CASE_ROWID)) AS VIOLATED_ROW_COUNT
         , COUNT(DISTINCT V.RULE_ID) AS RULE_COUNT
         , MAX(V.VIOLATION_SCORE) AS MAX_VIOLATION_SCORE
      FROM "INIT$_TB_RULEVIOL_SYMBOLIC" V
     WHERE V.RUN_SOURCE_TYPE = :runSourceType
       AND V.RUN_ID = :runId
       AND V.TARGET_OWNER = :targetOwner
       AND V.TARGET_TABLE = :targetTable
       AND V.TARGET_COLUMN IS NOT NULL
     GROUP BY V.TARGET_COLUMN
)
, VIOLATION_BY_COLUMN AS
(
    SELECT V.COLUMN_NAME
         , SUM(V.VIOLATION_COUNT) AS VIOLATION_COUNT
         , SUM(V.VIOLATED_ROW_COUNT) AS VIOLATED_ROW_COUNT
         , SUM(V.RULE_COUNT) AS RULE_COUNT
         , MAX(V.MAX_VIOLATION_SCORE) AS MAX_VIOLATION_SCORE
         , SUM(CASE WHEN V.RULE_TYPE = 'CATEGORICAL' THEN V.VIOLATION_COUNT ELSE 0 END) AS CATEGORICAL_VIOLATION_COUNT
         , SUM(CASE WHEN V.RULE_TYPE = 'CONTINUOUS' THEN V.VIOLATION_COUNT ELSE 0 END) AS CONTINUOUS_VIOLATION_COUNT
      FROM VIOLATION_BY_TYPE V
     GROUP BY V.COLUMN_NAME
)
SELECT V.COLUMN_NAME
     , C.DATA_TYPE
     , CC.COMMENTS AS COLUMN_COMMENT
     , V.VIOLATION_COUNT
     , V.VIOLATED_ROW_COUNT
     , V.RULE_COUNT
     , V.MAX_VIOLATION_SCORE
     , V.CATEGORICAL_VIOLATION_COUNT
     , V.CONTINUOUS_VIOLATION_COUNT
  FROM VIOLATION_BY_COLUMN V
  LEFT JOIN ALL_TAB_COLUMNS C
    ON C.OWNER = :targetOwner
   AND C.TABLE_NAME = :targetTable
   AND C.COLUMN_NAME = V.COLUMN_NAME
  LEFT JOIN ALL_COL_COMMENTS CC
    ON CC.OWNER = :targetOwner
   AND CC.TABLE_NAME = :targetTable
   AND CC.COLUMN_NAME = V.COLUMN_NAME
 ORDER BY V.VIOLATION_COUNT DESC
        , V.VIOLATED_ROW_COUNT DESC
        , V.COLUMN_NAME
;

-- [MCOMMON_STATS_AGGREGATE]
WITH NORMALIZED_VALUES AS
(
    SELECT /*+ MATERIALIZE NO_PARALLEL(T) */
           /* --DYNAMIC_COLUMNS-- */
      FROM /* --DYNAMIC_TABLE-- */ T
)
, LONG_VALUES AS
(
    SELECT /*+ MATERIALIZE */ COLUMN_NAME
         , NUMERIC_VALUE
      FROM NORMALIZED_VALUES
   UNPIVOT INCLUDE NULLS
     (
       NUMERIC_VALUE FOR COLUMN_NAME IN
       (
         /* --DYNAMIC_UNPIVOT-- */
       )
     )
)
, BASE_STATS AS
(
    SELECT COLUMN_NAME
         , COUNT(*) AS TOTAL_ROW_COUNT
         , COUNT(NUMERIC_VALUE) AS VALUE_COUNT
         , COUNT(DISTINCT NUMERIC_VALUE) AS DISTINCT_COUNT
         , SUM(NUMERIC_VALUE) AS SUM_VALUE
         , AVG(NUMERIC_VALUE) AS MEAN_VALUE
         , VAR_POP(NUMERIC_VALUE) AS VARIANCE_VALUE
         , STDDEV_POP(NUMERIC_VALUE) AS STDDEV_VALUE
         , MEDIAN(NUMERIC_VALUE) AS MEDIAN_VALUE
         , MIN(NUMERIC_VALUE) AS MIN_VALUE
         , PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY NUMERIC_VALUE) AS Q1_VALUE
         , PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY NUMERIC_VALUE) AS Q3_VALUE
         , MAX(NUMERIC_VALUE) AS MAX_VALUE
      FROM LONG_VALUES
     GROUP BY COLUMN_NAME
)
, CENTRAL_MOMENTS AS
(
    SELECT V.COLUMN_NAME
         , AVG(POWER(V.NUMERIC_VALUE - B.MEAN_VALUE, 3)) AS THIRD_MOMENT
         , AVG(POWER(V.NUMERIC_VALUE - B.MEAN_VALUE, 4)) AS FOURTH_MOMENT
      FROM LONG_VALUES V
      JOIN BASE_STATS B
        ON B.COLUMN_NAME = V.COLUMN_NAME
     WHERE V.NUMERIC_VALUE IS NOT NULL
     GROUP BY V.COLUMN_NAME
)
SELECT B.COLUMN_NAME
     , B.TOTAL_ROW_COUNT
     , B.VALUE_COUNT
     , B.TOTAL_ROW_COUNT - B.VALUE_COUNT AS NULL_COUNT
     , B.DISTINCT_COUNT
     , B.DISTINCT_COUNT / NULLIF(B.VALUE_COUNT, 0) AS DISTINCT_RATE
     , B.SUM_VALUE
     , B.MEAN_VALUE
     , B.VARIANCE_VALUE
     , B.STDDEV_VALUE
     , CASE
           WHEN B.VALUE_COUNT >= 3 AND B.VARIANCE_VALUE > 0
           THEN M.THIRD_MOMENT / POWER(B.VARIANCE_VALUE, 1.5)
       END AS SKEWNESS_VALUE
     , CASE
           WHEN B.VALUE_COUNT >= 4 AND B.VARIANCE_VALUE > 0
           THEN M.FOURTH_MOMENT / POWER(B.VARIANCE_VALUE, 2) - 3
       END AS KURTOSIS_VALUE
     , B.MEDIAN_VALUE
     , B.MIN_VALUE
     , B.Q1_VALUE
     , B.Q3_VALUE
     , B.MAX_VALUE
  FROM BASE_STATS B
  LEFT JOIN CENTRAL_MOMENTS M
    ON M.COLUMN_NAME = B.COLUMN_NAME
 ORDER BY B.COLUMN_NAME
;

