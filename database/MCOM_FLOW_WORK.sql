         , P.PROJECT_NAME
         , F.SCENARIO_ID
         , F.FLOW_NAME
         , R.RUN_TYPE
         , R.STATUS
         , R.MESSAGE
         , R.STARTED_AT
         , R.FINISHED_AT
         , R.CREATED_AT
      FROM INIT$_TB_FLOW_WORK_RUN R
      JOIN INIT$_TB_FLOW_WORK F
        ON F.FLOW_ID = R.FLOW_ID
      JOIN INIT$_TB_PROJECT P
        ON P.PROJECT_ID = F.PROJECT_ID
     WHERE 1=1
       AND F.MENU_CODE = :menuCode
       AND NVL(R.RUN_TYPE, 'MANUAL') <> 'QUICK_EDIT'
       AND (
            P.PROJECT_CODE LIKE 'QE\_%' ESCAPE '\'
         OR P.PROJECT_CODE LIKE 'QEDIT\_%' ESCAPE '\'
           )
       AND DBMS_LOB.INSTR(R.PLAN_JSON, '"runRequestToken"') > 0
       AND (:flowRunId IS NULL OR R.FLOW_RUN_ID = :flowRunId)
       AND (:includeAllUsers = 'Y' OR P.USER_ID = :userId)
)
, LEGACY_FLOW_TABLE_SCOPE AS (
    SELECT FN.FLOW_ID
         , MAX(J.SCENARIO_TABLE_ID) AS SCENARIO_TABLE_ID
         , COUNT(DISTINCT J.SCENARIO_TABLE_ID) AS SCENARIO_TABLE_COUNT
         , COUNT(DISTINCT J.WORK_JOB_ID) AS JOB_COUNT
      FROM INIT$_TB_FLOW_WORK_NODE FN
      JOIN INIT$_TB_DATA_WORK_JOB J
        ON J.WORK_JOB_ID = FN.REF_WORK_JOB_ID
     WHERE J.SCENARIO_TABLE_ID IS NOT NULL
       AND EXISTS (
            SELECT 1
              FROM LEGACY_RUN_SCOPE LRS
             WHERE LRS.FLOW_ID = FN.FLOW_ID
           )
     GROUP BY FN.FLOW_ID
)
, LEGACY_QUICK_RUNS AS (
    SELECT LRS.FLOW_RUN_ID
         , LRS.FLOW_ID
         , LRS.PROJECT_ID
         , LRS.PROJECT_CODE
         , LRS.PROJECT_NAME
         , LRS.SCENARIO_ID
         , S.SCENARIO_CODE
         , S.SCENARIO_NAME
         , FT.SCENARIO_TABLE_ID
         , ST.OWNER_NAME
         , ST.TABLE_NAME
         , ST.EDIT_OWNER_NAME
         , ST.EDIT_TABLE_NAME
         , UM.FILE_NAME
         , UM.FILE_SIZE
         , AT.NUM_ROWS AS ESTIMATED_ROW_COUNT
         , LRS.FLOW_NAME
         , FT.JOB_COUNT
         , LRS.RUN_TYPE
         , LRS.STATUS
         , LRS.MESSAGE
         , LRS.STARTED_AT
         , LRS.FINISHED_AT
         , LRS.CREATED_AT
         , 'N' AS SUMMARY_YN
      FROM LEGACY_RUN_SCOPE LRS
      JOIN INIT$_TB_SCENARIO S
        ON S.SCENARIO_ID = LRS.SCENARIO_ID
       AND S.PROJECT_ID = LRS.PROJECT_ID
      JOIN LEGACY_FLOW_TABLE_SCOPE FT
        ON FT.FLOW_ID = LRS.FLOW_ID
       AND FT.SCENARIO_TABLE_COUNT = 1
      JOIN INIT$_TB_TABLES ST
        ON ST.SCENARIO_TABLE_ID = FT.SCENARIO_TABLE_ID
       AND ST.PROJECT_ID = LRS.PROJECT_ID
       AND ST.SCENARIO_ID = LRS.SCENARIO_ID
      LEFT JOIN INIT$_TB_UPLOAD_TABLE_META UM
        ON UM.OWNER_NAME = ST.OWNER_NAME
       AND UM.TABLE_NAME = ST.TABLE_NAME
      LEFT JOIN ALL_TABLES AT
        ON AT.OWNER = ST.OWNER_NAME
       AND AT.TABLE_NAME = ST.TABLE_NAME
)
