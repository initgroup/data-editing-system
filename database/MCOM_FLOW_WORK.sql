         , STARTED_AT
         , FINISHED_AT
         , CREATED_AT
         , SUMMARY_YN
      FROM LEGACY_QUICK_RUNS
)
, ELIGIBLE_RUNS AS (
    SELECT QR.*
         , COUNT(*) OVER () AS TOTAL_COUNT
         , ROW_NUMBER() OVER (
               ORDER BY COALESCE(QR.STARTED_AT, QR.CREATED_AT) DESC
                      , QR.FLOW_RUN_ID DESC
           ) AS RN
      FROM QUICK_RUNS QR
)
, PAGED_RUNS AS (
    SELECT /*+ MATERIALIZE */ *
      FROM ELIGIBLE_RUNS
     WHERE RN > :offset
       AND RN <= :endRow
)
, NODE_COUNTS AS (
    SELECT NR.FLOW_RUN_ID
         , COUNT(*) AS NODE_COUNT
         , SUM(CASE WHEN NR.STATUS = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_NODE_COUNT
         , SUM(CASE WHEN NR.STATUS IN ('FAILED', 'ERROR', 'CANCELLED') THEN 1 ELSE 0 END) AS FAILED_NODE_COUNT
      FROM INIT$_TB_FLOW_WORK_NODE_RUN NR
     WHERE EXISTS (
            SELECT 1
              FROM PAGED_RUNS PR
             WHERE PR.FLOW_RUN_ID = NR.FLOW_RUN_ID
           )
     GROUP BY NR.FLOW_RUN_ID
)
SELECT PR.FLOW_RUN_ID
     , PR.FLOW_ID
     , PR.PROJECT_ID
     , COALESCE(QS.PROJECT_CODE, PR.PROJECT_CODE) AS PROJECT_CODE
     , COALESCE(QS.PROJECT_NAME, PR.PROJECT_NAME) AS PROJECT_NAME
     , QS.PROJECT_CREATED_AT
     , PR.SCENARIO_ID
     , COALESCE(QS.SCENARIO_CODE, PR.SCENARIO_CODE) AS SCENARIO_CODE
     , COALESCE(QS.SCENARIO_NAME, PR.SCENARIO_NAME) AS SCENARIO_NAME
     , QS.SCENARIO_CREATED_AT
     , COALESCE(QS.SCENARIO_TABLE_ID, PR.SCENARIO_TABLE_ID) AS SCENARIO_TABLE_ID
     , COALESCE(QS.OWNER_NAME, PR.OWNER_NAME) AS OWNER_NAME
     , COALESCE(QS.TABLE_NAME, PR.TABLE_NAME) AS TABLE_NAME
     , COALESCE(QS.EDIT_OWNER_NAME, PR.EDIT_OWNER_NAME) AS EDIT_OWNER_NAME
     , COALESCE(QS.EDIT_TABLE_NAME, PR.EDIT_TABLE_NAME) AS EDIT_TABLE_NAME
     , COALESCE(QS.FILE_NAME, PR.FILE_NAME) AS FILE_NAME
     , COALESCE(QS.FILE_SIZE, PR.FILE_SIZE) AS FILE_SIZE
     , COALESCE(QS.ESTIMATED_ROW_COUNT, PR.ESTIMATED_ROW_COUNT) AS ESTIMATED_ROW_COUNT
     , COALESCE(QS.FLOW_NAME, PR.FLOW_NAME) AS FLOW_NAME
     , COALESCE(QS.JOB_COUNT, PR.JOB_COUNT) AS JOB_COUNT
     , PR.RUN_TYPE
     , PR.STATUS
     , PR.MESSAGE
     , PR.STARTED_AT
     , PR.FINISHED_AT
     , PR.CREATED_AT
     , NVL(NC.NODE_COUNT, 0) AS NODE_COUNT
     , NVL(NC.SUCCESS_NODE_COUNT, 0) AS SUCCESS_NODE_COUNT
     , NVL(NC.FAILED_NODE_COUNT, 0) AS FAILED_NODE_COUNT
     , PR.TOTAL_COUNT
  FROM PAGED_RUNS PR
  LEFT JOIN INIT$_TB_FLOW_WORK_RUN SR
    ON SR.FLOW_RUN_ID = PR.FLOW_RUN_ID
   AND PR.SUMMARY_YN = 'Y'
  LEFT JOIN JSON_TABLE(
       SR.PLAN_JSON
     , '$.quickEditSummary' NULL ON ERROR
       COLUMNS (
           PROJECT_CODE VARCHAR2(100) PATH '$.projectCode'
         , PROJECT_NAME VARCHAR2(200) PATH '$.projectName'
         , PROJECT_CREATED_AT VARCHAR2(64) PATH '$.projectCreatedAt'
         , SCENARIO_CODE VARCHAR2(100) PATH '$.scenarioCode'
         , SCENARIO_NAME VARCHAR2(200) PATH '$.scenarioName'
         , SCENARIO_CREATED_AT VARCHAR2(64) PATH '$.scenarioCreatedAt'
         , SCENARIO_TABLE_ID NUMBER PATH '$.scenarioTableId'
         , OWNER_NAME VARCHAR2(128) PATH '$.ownerName'
         , TABLE_NAME VARCHAR2(128) PATH '$.tableName'
         , EDIT_OWNER_NAME VARCHAR2(128) PATH '$.editOwnerName'
         , EDIT_TABLE_NAME VARCHAR2(128) PATH '$.editTableName'
         , FILE_NAME VARCHAR2(255) PATH '$.fileName'
         , FILE_SIZE NUMBER PATH '$.fileSize'
         , ESTIMATED_ROW_COUNT NUMBER PATH '$.estimatedRowCount'
         , FLOW_NAME VARCHAR2(200) PATH '$.flowName'
         , JOB_COUNT NUMBER PATH '$.jobCount'
       )
     ) QS
    ON 1=1
  LEFT JOIN NODE_COUNTS NC
    ON NC.FLOW_RUN_ID = PR.FLOW_RUN_ID
 ORDER BY PR.RN
;

