         , CAST(NULL AS VARCHAR2(128)) AS EDIT_TABLE_NAME
         , CAST(NULL AS VARCHAR2(255)) AS FILE_NAME
         , CAST(NULL AS NUMBER) AS FILE_SIZE
         , CAST(NULL AS NUMBER) AS ESTIMATED_ROW_COUNT
         , F.FLOW_NAME
         , CAST(NULL AS NUMBER) AS JOB_COUNT
         , R.RUN_TYPE
         , R.STATUS
         , R.MESSAGE
         , R.STARTED_AT
         , R.FINISHED_AT
         , R.CREATED_AT
         , 'Y' AS SUMMARY_YN
      FROM INIT$_TB_FLOW_WORK_RUN R
      JOIN INIT$_TB_FLOW_WORK F
        ON F.FLOW_ID = R.FLOW_ID
      JOIN INIT$_TB_PROJECT P
        ON P.PROJECT_ID = F.PROJECT_ID
