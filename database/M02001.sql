-- [M02001_UPLOAD_TABLE_TREE]
SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS OWNER
     , T.TABLE_NAME
     , C.COMMENTS
     , T.NUM_ROWS
     , T.LAST_ANALYZED
  FROM USER_TABLES T
  JOIN INIT$_TB_UPLOAD_TABLE_META M
    ON M.OWNER_NAME = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
   AND M.TABLE_NAME = T.TABLE_NAME
   AND M.PROJECT_ID = :projectId
   AND NVL(M.LOAD_STATUS, 'READY') = 'READY'
  LEFT OUTER JOIN USER_TAB_COMMENTS C
    ON C.TABLE_NAME = T.TABLE_NAME
 WHERE T.TABLE_NAME LIKE :tablePrefix || '%'
   AND T.TABLE_NAME NOT LIKE 'BIN$%'
   AND T.NESTED = 'NO'
   AND T.SECONDARY = 'N'
 ORDER BY T.TABLE_NAME
;

