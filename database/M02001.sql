-- [M02001_STALE_UPLOAD_STAGE_TABLES]
SELECT T.TABLE_NAME
  FROM USER_TABLES T
  JOIN USER_OBJECTS O
    ON O.OBJECT_NAME = T.TABLE_NAME
   AND O.OBJECT_TYPE = 'TABLE'
 WHERE REGEXP_LIKE(T.TABLE_NAME, '^INITSTG\$_[A-F0-9]{32}$')
   AND O.CREATED < SYSDATE - (:maxAgeSeconds / 86400)
 ORDER BY O.CREATED
;

-- [M02001_STALE_LOADING_UPLOAD_TABLES]
SELECT M.TABLE_NAME
  FROM INIT$_TB_UPLOAD_TABLE_META M
 WHERE M.OWNER_NAME = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
   AND M.LOAD_STATUS = 'LOADING'
   AND REGEXP_LIKE(M.TABLE_NAME, '^INITUP\$_[A-Z0-9_$#_]*[0-9]{13}$')
   AND NVL(M.UPDATED_AT, M.CREATED_AT) < SYSTIMESTAMP - NUMTODSINTERVAL(:maxAgeSeconds, 'SECOND')
 ORDER BY NVL(M.UPDATED_AT, M.CREATED_AT)
;

