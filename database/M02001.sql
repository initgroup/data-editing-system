-- [M02001_UPLOAD_TABLE_META_MERGE]
MERGE INTO "INIT$_TB_UPLOAD_TABLE_META" T
USING (
    SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS OWNER_NAME
         , :tableName AS TABLE_NAME
         , :projectId AS PROJECT_ID
         , :fileExtension AS FILE_EXTENSION
         , :fileName AS FILE_NAME
         , :fileSize AS FILE_SIZE
         , :uploadId AS UPLOAD_ID
         , :rowCount AS ROW_COUNT
         , :contentSha256 AS CONTENT_SHA256
         , :loadStatus AS LOAD_STATUS
      FROM DUAL
) S
   ON (T.OWNER_NAME = S.OWNER_NAME AND T.TABLE_NAME = S.TABLE_NAME)
 WHEN MATCHED THEN
      UPDATE
         SET T.PROJECT_ID = S.PROJECT_ID
           , T.FILE_EXTENSION = S.FILE_EXTENSION
           , T.FILE_NAME = S.FILE_NAME
           , T.FILE_SIZE = S.FILE_SIZE
           , T.UPLOAD_ID = S.UPLOAD_ID
           , T.ROW_COUNT = S.ROW_COUNT
           , T.CONTENT_SHA256 = S.CONTENT_SHA256
           , T.LOAD_STATUS = S.LOAD_STATUS
           , T.UPDATED_AT = SYSTIMESTAMP
 WHEN NOT MATCHED THEN
      INSERT (
          OWNER_NAME
        , TABLE_NAME
        , PROJECT_ID
        , FILE_EXTENSION
        , FILE_NAME
        , FILE_SIZE
        , UPLOAD_ID
        , ROW_COUNT
        , CONTENT_SHA256
        , LOAD_STATUS
      ) VALUES (
          S.OWNER_NAME
        , S.TABLE_NAME
        , S.PROJECT_ID
        , S.FILE_EXTENSION
        , S.FILE_NAME
        , S.FILE_SIZE
        , S.UPLOAD_ID
        , S.ROW_COUNT
        , S.CONTENT_SHA256
        , S.LOAD_STATUS
      )
;

