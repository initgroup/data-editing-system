-- [M02002_TABLE_COLUMN_MAP_MERGE]
MERGE INTO INIT$_TB_TABLE_COLUMN_MAP T
USING (
    SELECT :scenarioTableId AS SCENARIO_TABLE_ID
         , :sourceColumnName AS SOURCE_COLUMN_NAME
         , :managedColumnName AS MANAGED_COLUMN_NAME
         , :mappingType AS MAPPING_TYPE
      FROM DUAL
) S
   ON (
          T.SCENARIO_TABLE_ID = S.SCENARIO_TABLE_ID
      AND T.SOURCE_COLUMN_NAME = S.SOURCE_COLUMN_NAME
   )
 WHEN MATCHED THEN
      UPDATE
         SET T.MANAGED_COLUMN_NAME = S.MANAGED_COLUMN_NAME
           , T.MAPPING_TYPE = S.MAPPING_TYPE
 WHEN NOT MATCHED THEN
      INSERT (
          SCENARIO_TABLE_ID
        , SOURCE_COLUMN_NAME
        , MANAGED_COLUMN_NAME
        , MAPPING_TYPE
      ) VALUES (
          S.SCENARIO_TABLE_ID
        , S.SOURCE_COLUMN_NAME
        , S.MANAGED_COLUMN_NAME
        , S.MAPPING_TYPE
      )
;

