
-- [M02002_TABLE_TREE]
WITH REGISTERED_TABLES AS (
    SELECT DISTINCT ST.OWNER_NAME
         , ST.TABLE_NAME
      FROM INIT$_TB_TABLES ST
     WHERE ST.PROJECT_ID = :projectId
       AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
    UNION
    SELECT DISTINCT ST.EDIT_OWNER_NAME AS OWNER_NAME
         , ST.EDIT_TABLE_NAME AS TABLE_NAME
      FROM INIT$_TB_TABLES ST
     WHERE ST.PROJECT_ID = :projectId
       AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
       AND ST.EDIT_OWNER_NAME IS NOT NULL
       AND ST.EDIT_TABLE_NAME IS NOT NULL
)
, IMPORTED_ORIGINAL_TABLES AS (
    SELECT DISTINCT ST.ORIGINAL_OWNER_NAME AS OWNER_NAME
         , ST.ORIGINAL_TABLE_NAME AS TABLE_NAME
      FROM INIT$_TB_TABLES ST
     WHERE ST.PROJECT_ID = :projectId
       AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
       AND ST.TABLE_NAME LIKE 'INITUP$%'
       AND ST.ORIGINAL_OWNER_NAME IS NOT NULL
       AND ST.ORIGINAL_TABLE_NAME IS NOT NULL
       AND (
              ST.ORIGINAL_OWNER_NAME <> ST.OWNER_NAME
           OR ST.ORIGINAL_TABLE_NAME <> ST.TABLE_NAME
       )
)
, PROJECT_UPLOAD_TABLES AS (
    SELECT UM.OWNER_NAME
         , UM.TABLE_NAME
         , UM.FILE_EXTENSION
         , UM.FILE_NAME
         , UM.FILE_SIZE
      FROM "INIT$_TB_UPLOAD_TABLE_META" UM
     WHERE UM.PROJECT_ID = :projectId
)
, PROJECT_MANAGED_TABLES AS (
    SELECT UM.OWNER_NAME
         , UM.TABLE_NAME
      FROM "INIT$_TB_UPLOAD_TABLE_META" UM
     WHERE UM.PROJECT_ID = :projectId
       AND UM.TABLE_NAME LIKE 'INITUP$%'
    UNION
    SELECT UM.OWNER_NAME
         , 'INITDN$' || SUBSTR(UM.TABLE_NAME, LENGTH('INITUP$') + 1) AS TABLE_NAME
      FROM "INIT$_TB_UPLOAD_TABLE_META" UM
     WHERE UM.PROJECT_ID = :projectId
       AND UM.TABLE_NAME LIKE 'INITUP$%'
    UNION
    SELECT ST.OWNER_NAME
         , ST.TABLE_NAME
      FROM INIT$_TB_TABLES ST
     WHERE ST.PROJECT_ID = :projectId
       AND ST.TABLE_NAME LIKE 'INITUP$%'
    UNION
    SELECT ST.EDIT_OWNER_NAME AS OWNER_NAME
         , ST.EDIT_TABLE_NAME AS TABLE_NAME
      FROM INIT$_TB_TABLES ST
     WHERE ST.PROJECT_ID = :projectId
       AND ST.EDIT_OWNER_NAME IS NOT NULL
       AND ST.EDIT_TABLE_NAME LIKE 'INITDN$%'
)
, BASE_TABLES AS (
    SELECT T.OWNER
         , T.TABLE_NAME
         , T.NESTED
         , T.SECONDARY
         , C.COMMENTS
      FROM ALL_TABLES T
      LEFT JOIN ALL_TAB_COMMENTS C
        ON C.OWNER = T.OWNER
       AND C.TABLE_NAME = T.TABLE_NAME
     WHERE T.NESTED = 'NO'
       AND T.SECONDARY = 'N'
       AND T.TABLE_NAME NOT LIKE 'BIN$%'
       AND (:ownerPattern IS NULL OR T.OWNER LIKE :ownerPattern)
       AND (:excludePattern1 IS NULL OR T.TABLE_NAME NOT LIKE :excludePattern1)
       AND (:excludePattern2 IS NULL OR T.TABLE_NAME NOT LIKE :excludePattern2)
       AND (:excludePattern3 IS NULL OR T.TABLE_NAME NOT LIKE :excludePattern3)
       AND (:excludePattern4 IS NULL OR T.TABLE_NAME NOT LIKE :excludePattern4)
       AND (:excludePattern5 IS NULL OR T.TABLE_NAME NOT LIKE :excludePattern5)
       AND (
              :keyword IS NULL
           OR UPPER(T.OWNER) LIKE :keyword
           OR UPPER(T.TABLE_NAME) LIKE :keyword
           OR UPPER(C.COMMENTS) LIKE :keyword
       )
)
, TABLE_CANDIDATES AS (
    SELECT B.OWNER
         , B.TABLE_NAME
         , B.NESTED
         , B.SECONDARY
         , B.COMMENTS
         , PUT.FILE_EXTENSION AS ORIGINAL_FILE_EXTENSION
         , PUT.FILE_NAME AS ORIGINAL_FILE_NAME
         , PUT.FILE_SIZE AS ORIGINAL_FILE_SIZE
      FROM BASE_TABLES B
      LEFT JOIN PROJECT_UPLOAD_TABLES PUT
        ON PUT.OWNER_NAME = B.OWNER
       AND PUT.TABLE_NAME = B.TABLE_NAME
      JOIN PROJECT_MANAGED_TABLES PMT
        ON PMT.OWNER_NAME = B.OWNER
       AND PMT.TABLE_NAME = B.TABLE_NAME
     WHERE (B.TABLE_NAME LIKE 'INITUP$%' OR B.TABLE_NAME LIKE 'INITDN$%')
    UNION ALL
    SELECT B.OWNER
         , B.TABLE_NAME
         , B.NESTED
         , B.SECONDARY
         , B.COMMENTS
         , CAST(NULL AS VARCHAR2(20)) AS ORIGINAL_FILE_EXTENSION
         , CAST(NULL AS VARCHAR2(500)) AS ORIGINAL_FILE_NAME
         , CAST(NULL AS NUMBER) AS ORIGINAL_FILE_SIZE
      FROM BASE_TABLES B
     WHERE B.TABLE_NAME NOT LIKE 'INITUP$%'
       AND B.TABLE_NAME NOT LIKE 'INITDN$%'
)
SELECT OWNER
     , TABLE_NAME
     , COMMENTS
     , IS_REGISTERED
     , IS_MANAGED_SOURCE
     , ORIGINAL_FILE_EXTENSION
     , ORIGINAL_FILE_NAME
     , ORIGINAL_FILE_SIZE
  FROM (
    SELECT T.OWNER
         , T.TABLE_NAME
         , T.COMMENTS
         , T.ORIGINAL_FILE_EXTENSION
         , T.ORIGINAL_FILE_NAME
         , T.ORIGINAL_FILE_SIZE
         , CASE
               WHEN RT.TABLE_NAME IS NOT NULL
               THEN 'Y'
               ELSE 'N'
           END AS IS_REGISTERED
         , CASE
               WHEN T.TABLE_NAME LIKE 'INITUP$%'
                AND EXISTS (
                    SELECT 1
                      FROM ALL_TAB_COLUMNS TC
                     WHERE TC.OWNER = T.OWNER
                       AND TC.TABLE_NAME = T.TABLE_NAME
                       AND TC.COLUMN_NAME = 'FILE_ROW_NO'
                )
               THEN 'Y'
               ELSE 'N'
           END AS IS_MANAGED_SOURCE
         , ROW_NUMBER() OVER (ORDER BY T.OWNER, T.TABLE_NAME) AS RN
      FROM TABLE_CANDIDATES T
      LEFT JOIN REGISTERED_TABLES RT
        ON RT.OWNER_NAME = T.OWNER
       AND RT.TABLE_NAME = T.TABLE_NAME
      LEFT JOIN IMPORTED_ORIGINAL_TABLES IOT
        ON IOT.OWNER_NAME = T.OWNER
       AND IOT.TABLE_NAME = T.TABLE_NAME
     WHERE IOT.TABLE_NAME IS NULL
       AND (
              :registeredOnly = 'N'
           OR RT.TABLE_NAME IS NOT NULL
           )
  )
 WHERE RN > :offset
   AND RN <= :endRow
 ORDER BY RN
;

-- [M02002_TABLE_INFO]
SELECT T.OWNER
     , T.TABLE_NAME
     , C.COMMENTS
     , (
         SELECT MAX(ST.ORIGINAL_OWNER_NAME)
           FROM INIT$_TB_TABLES ST
          WHERE ST.OWNER_NAME = T.OWNER
            AND ST.TABLE_NAME = T.TABLE_NAME
            AND ST.DATA_ORIGIN_TYPE = 'DB_TABLE_IMPORT'
            AND (:projectId IS NULL OR ST.PROJECT_ID = :projectId)
            AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
       ) AS ORIGINAL_OWNER_NAME
     , (
         SELECT MAX(ST.ORIGINAL_TABLE_NAME)
           FROM INIT$_TB_TABLES ST
          WHERE ST.OWNER_NAME = T.OWNER
            AND ST.TABLE_NAME = T.TABLE_NAME
            AND ST.DATA_ORIGIN_TYPE = 'DB_TABLE_IMPORT'
            AND (:projectId IS NULL OR ST.PROJECT_ID = :projectId)
            AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
       ) AS ORIGINAL_TABLE_NAME
     , TO_CHAR(O.CREATED, 'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT
     , T.NUM_ROWS
     , T.LAST_ANALYZED
  FROM ALL_TABLES T
  LEFT JOIN ALL_TAB_COMMENTS C
    ON C.OWNER = T.OWNER
   AND C.TABLE_NAME = T.TABLE_NAME
  LEFT JOIN ALL_OBJECTS O
    ON O.OWNER = T.OWNER
   AND O.OBJECT_NAME = T.TABLE_NAME
   AND O.OBJECT_TYPE = 'TABLE'
 WHERE T.OWNER = :owner
   AND T.TABLE_NAME = :tableName
;

-- [M02002_TABLE_COLUMNS]
SELECT C.OWNER
     , C.TABLE_NAME AS TABLE_ID
     , TC.COMMENTS AS TABLE_COMMENT
     , C.COLUMN_ID
     , C.COLUMN_NAME
     , CC.COMMENTS AS COLUMN_COMMENT
     , C.DATA_TYPE
     , C.DATA_LENGTH
     , C.CHAR_LENGTH
     , C.DATA_PRECISION
     , C.DATA_SCALE
     , C.NULLABLE
     , C.DATA_DEFAULT
     , CASE
        WHEN PK.COLUMN_NAME IS NOT NULL THEN 'Y'
        ELSE 'N'
    END AS PRIMARY_KEY_YN
     , C.NUM_DISTINCT
     , C.NUM_NULLS
     , C.DENSITY
     , C.LAST_ANALYZED
  FROM ALL_TAB_COLUMNS C
  LEFT JOIN ALL_TAB_COMMENTS TC
    ON TC.OWNER = C.OWNER
   AND TC.TABLE_NAME = C.TABLE_NAME
  LEFT JOIN ALL_COL_COMMENTS CC
    ON CC.OWNER = C.OWNER
   AND CC.TABLE_NAME = C.TABLE_NAME
   AND CC.COLUMN_NAME = C.COLUMN_NAME
  LEFT JOIN (
        SELECT ACC.OWNER, ACC.TABLE_NAME, ACC.COLUMN_NAME
          FROM ALL_CONSTRAINTS AC
          JOIN ALL_CONS_COLUMNS ACC
            ON ACC.OWNER = AC.OWNER
           AND ACC.CONSTRAINT_NAME = AC.CONSTRAINT_NAME
         WHERE AC.CONSTRAINT_TYPE = 'P'
  ) PK
    ON PK.OWNER = C.OWNER
   AND PK.TABLE_NAME = C.TABLE_NAME
   AND PK.COLUMN_NAME = C.COLUMN_NAME
 WHERE C.OWNER = :owner
   AND C.TABLE_NAME = :tableName
 ORDER BY C.COLUMN_ID
;

