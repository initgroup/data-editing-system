-- [M02002_SCENARIO_TABLE_LIST]
SELECT ST.SCENARIO_TABLE_ID
     , ST.PROJECT_ID
     , ST.SCENARIO_ID
     , ST.OWNER_NAME
     , ST.TABLE_NAME
     , ST.ORIGINAL_OWNER_NAME
     , ST.ORIGINAL_TABLE_NAME
     , ST.EDIT_OWNER_NAME
     , ST.EDIT_TABLE_NAME
     , ST.DATA_ORIGIN_TYPE
     , ST.CASE_ID_COLUMN
     , ST.IMPORTED_AT
     , ST.TABLE_COMMENT
     , ST.USE_YN
     , ST.SORT_ORDER
     , ST.CREATED_AT
     , ST.UPDATED_AT
     , SC.COMMENTS AS SOURCE_TABLE_COMMENT
     , TO_CHAR(SO.CREATED, 'YYYY-MM-DD HH24:MI:SS') AS SOURCE_CREATED_AT
     , CASE
           WHEN EO.OBJECT_NAME IS NOT NULL THEN 'Y'
           ELSE 'N'
       END AS EDIT_TABLE_EXISTS
     , EC.COMMENTS AS EDIT_TABLE_COMMENT
     , TO_CHAR(EO.CREATED, 'YYYY-MM-DD HH24:MI:SS') AS EDIT_CREATED_AT
     , OC.COMMENTS AS ORIGINAL_TABLE_COMMENT
     , TO_CHAR(OO.CREATED, 'YYYY-MM-DD HH24:MI:SS') AS ORIGINAL_CREATED_AT
     , UM.FILE_EXTENSION AS ORIGINAL_FILE_EXTENSION
     , UM.FILE_NAME AS ORIGINAL_FILE_NAME
     , UM.FILE_SIZE AS ORIGINAL_FILE_SIZE
  FROM INIT$_TB_TABLES ST
  LEFT JOIN "INIT$_TB_UPLOAD_TABLE_META" UM
    ON UM.OWNER_NAME = ST.OWNER_NAME
   AND UM.TABLE_NAME = ST.TABLE_NAME
  LEFT JOIN ALL_TAB_COMMENTS SC
    ON SC.OWNER = ST.OWNER_NAME
   AND SC.TABLE_NAME = ST.TABLE_NAME
  LEFT JOIN ALL_OBJECTS SO
    ON SO.OWNER = ST.OWNER_NAME
   AND SO.OBJECT_NAME = ST.TABLE_NAME
   AND SO.OBJECT_TYPE = 'TABLE'
  LEFT JOIN ALL_TAB_COMMENTS EC
    ON EC.OWNER = ST.EDIT_OWNER_NAME
   AND EC.TABLE_NAME = ST.EDIT_TABLE_NAME
  LEFT JOIN ALL_OBJECTS EO
    ON EO.OWNER = ST.EDIT_OWNER_NAME
   AND EO.OBJECT_NAME = ST.EDIT_TABLE_NAME
   AND EO.OBJECT_TYPE = 'TABLE'
  LEFT JOIN ALL_TAB_COMMENTS OC
    ON OC.OWNER = ST.ORIGINAL_OWNER_NAME
   AND OC.TABLE_NAME = ST.ORIGINAL_TABLE_NAME
  LEFT JOIN ALL_OBJECTS OO
    ON OO.OWNER = ST.ORIGINAL_OWNER_NAME
   AND OO.OBJECT_NAME = ST.ORIGINAL_TABLE_NAME
   AND OO.OBJECT_TYPE = 'TABLE'
 WHERE ST.PROJECT_ID = :projectId
   AND (:scenarioId IS NULL OR ST.SCENARIO_ID = :scenarioId)
 ORDER BY ST.SORT_ORDER NULLS LAST, ST.OWNER_NAME, ST.TABLE_NAME, ST.SCENARIO_TABLE_ID
;

