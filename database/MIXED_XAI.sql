-- [XAI_FLOW_COLUMN_COMMENTS]
SELECT C.COLUMN_NAME
     , C.COMMENTS
  FROM ALL_COL_COMMENTS C
 WHERE 1=1
   AND EXISTS
       (
        SELECT 1
          FROM INIT$_TB_XAI_RUN R
         WHERE R.RUN_SOURCE_TYPE = 'FLOW_WORK'
           AND R.RUN_ID = :runId
           AND R.TARGET_OWNER = C.OWNER
           AND R.TARGET_TABLE = C.TABLE_NAME
           AND (:owner IS NULL OR R.TARGET_OWNER = :owner)
           AND (:tableName IS NULL OR R.TARGET_TABLE = :tableName)
       )
;

-- [XAI_FLOW_RULES_PAGE]
SELECT TARGET_OWNER
     , TARGET_TABLE
     , RULE_ID
     , RULE_TEXT
     , CONDITION_JSON
     , SUPPORT_COUNT
     , ANOMALY_COUNT
     , RULE_PURITY
     , MATCH_COUNT
     , VALIDATION_JSON
     , STATUS
  FROM INIT$_TB_RULEDISC_XAI
 WHERE 1=1
   AND RUN_SOURCE_TYPE = 'FLOW_WORK'
   AND RUN_ID = :runId
   AND (:owner IS NULL OR TARGET_OWNER = :owner)
   AND (:tableName IS NULL OR TARGET_TABLE = :tableName)
 ORDER BY TARGET_OWNER
        , TARGET_TABLE
        , RULE_ID
OFFSET :offset ROWS FETCH NEXT :pageSize ROWS ONLY
;

