-- [XAI_RUN_ACCESS]
SELECT P.USER_ID
  FROM INIT$_TB_FLOW_WORK_RUN R
  JOIN INIT$_TB_FLOW_WORK F
    ON F.FLOW_ID = R.FLOW_ID
  JOIN INIT$_TB_PROJECT P
    ON P.PROJECT_ID = F.PROJECT_ID
  JOIN INIT$_TB_TABLES T
    ON T.PROJECT_ID = F.PROJECT_ID
   AND T.SCENARIO_ID = F.SCENARIO_ID
 WHERE :runSourceType = 'FLOW_WORK'
   AND R.FLOW_RUN_ID = :runId
   AND P.USER_ID = :userId
   AND ((T.OWNER_NAME = :owner AND T.TABLE_NAME = :tableName)
     OR (T.EDIT_OWNER_NAME = :owner AND T.EDIT_TABLE_NAME = :tableName))
UNION ALL
SELECT P.USER_ID
  FROM INIT$_TB_DATA_WORK_RUN R
  JOIN INIT$_TB_DATA_WORK_JOB J
    ON J.WORK_JOB_ID = R.WORK_JOB_ID
  JOIN INIT$_TB_PROJECT P
    ON P.PROJECT_ID = J.PROJECT_ID
 WHERE :runSourceType = 'DATA_WORK'
   AND R.DATA_RUN_ID = :runId
   AND P.USER_ID = :userId
   AND J.OWNER_NAME = :owner
   AND J.TABLE_NAME = :tableName
;

-- [XAI_FLOW_ACCESS]
SELECT F.FLOW_ID
  FROM INIT$_TB_FLOW_WORK_RUN R
  JOIN INIT$_TB_FLOW_WORK F
    ON F.FLOW_ID = R.FLOW_ID
  JOIN INIT$_TB_PROJECT P
    ON P.PROJECT_ID = F.PROJECT_ID
 WHERE R.FLOW_RUN_ID = :runId
   AND (:includeAllUsers = 'Y' OR P.USER_ID = :userId)
;

-- [XAI_DATA_DISCOVERY_SCOPE]
SELECT A.WORK_JOB_ID
  FROM INIT$_TB_DATA_WORK_RUN AR
  JOIN INIT$_TB_DATA_WORK_JOB A
    ON A.WORK_JOB_ID = AR.WORK_JOB_ID
  JOIN INIT$_TB_DATA_WORK_RUN BR
    ON BR.DATA_RUN_ID = :discoveryRunId
  JOIN INIT$_TB_DATA_WORK_JOB B
    ON B.WORK_JOB_ID = BR.WORK_JOB_ID
   AND B.PROJECT_ID = A.PROJECT_ID
   AND B.SCENARIO_ID = A.SCENARIO_ID
   AND B.OWNER_NAME = A.OWNER_NAME
   AND B.TABLE_NAME = A.TABLE_NAME
 WHERE AR.DATA_RUN_ID = :runId
   AND A.OWNER_NAME = :owner
   AND A.TABLE_NAME = :tableName
;

